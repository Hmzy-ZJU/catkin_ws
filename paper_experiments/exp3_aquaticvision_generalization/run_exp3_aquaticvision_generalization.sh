#!/usr/bin/env bash
set -euo pipefail

# Exp. 3: AquaticVision ROS-online generalization.

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
EXP_DIR="$SCRIPT_DIR"
CONFIG_FILE="${EXP3_CONFIG:-$EXP_DIR/run_config/exp3_config.env}"

if [ ! -f "$CONFIG_FILE" ]; then
  echo "[ERROR] missing config: $CONFIG_FILE" >&2
  exit 2
fi

# shellcheck disable=SC1090
source "$CONFIG_FILE"

RUN_TAG="${RUN_TAG:-exp3_aquaticvision_$(date +%Y%m%d_%H%M%S)}"
RESULT_ROOT="$EXP_DIR/raw_results/${RUN_TAG}"
SUMMARY="$EXP_DIR/processed_results/exp3_all_runs_${RUN_TAG}.csv"
MASTER_LOG="$EXP_DIR/logs/${RUN_TAG}.log"
IMAGE_PUBLISHER="$EXP_DIR/tools/publish_stereo_images_ros.py"

mkdir -p "$RESULT_ROOT" "$EXP_DIR/processed_results" "$EXP_DIR/logs"
: > "$MASTER_LOG"

log() { printf '[%s] %s\n' "$(date '+%F %T')" "$*" | tee -a "$MASTER_LOG"; }
csv_quote() { printf '"%s"' "$(printf '%s' "$1" | sed 's/"/""/g')"; }
write_row() { local first=1 value; for value in "$@"; do if [ "$first" = "1" ]; then first=0; else printf ',' >> "$SUMMARY"; fi; csv_quote "$value" >> "$SUMMARY"; done; printf '\n' >> "$SUMMARY"; }

normalize_mode() {
  local upper
  upper="$(printf '%s' "$1" | tr '[:lower:]-' '[:upper:]_')"
  case "$upper" in
    ORB_SLAM3|ORBSLAM3|ORB3|BASELINE) printf '%s\n' ORB_SLAM3 ;;
    IDPS) printf '%s\n' IDPS ;;
    IDKD) printf '%s\n' IDKD ;;
    IDVO|UW_IDVO|UWIDVO) printf '%s\n' IDVO ;;
    *) return 1 ;;
  esac
}

mode_switches() {
  case "$1" in
    ORB_SLAM3) printf '%s %s\n' 0 0 ;;
    IDPS) printf '%s %s\n' 1 0 ;;
    IDKD) printf '%s %s\n' 0 1 ;;
    IDVO) printf '%s %s\n' 1 1 ;;
    *) return 1 ;;
  esac
}

normalize_source() {
  local lower
  lower="$(printf '%s' "$1" | tr '[:upper:]' '[:lower:]')"
  case "$lower" in
    stereo_images|stereo-images|images|image_pairs|image-pairs) printf '%s\n' stereo_images ;;
    rosbag|bag) printf '%s\n' rosbag ;;
    *) return 1 ;;
  esac
}

count_lines() {
  local file="$1"
  [ -f "$file" ] || { printf '0\n'; return; }
  awk 'NF && $1 !~ /^#/ { c++ } END { print c+0 }' "$file"
}

trajectory_span_sec() {
  local file="$1"
  [ -s "$file" ] || { printf '0.000\n'; return; }
  python3 - "$file" <<'PY'
import math
import sys

times = []
with open(sys.argv[1]) as f:
    for line in f:
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        if len(parts) < 2:
            continue
        try:
            t = float(parts[0])
            if abs(t) > 1e12:
                t *= 1e-9
            if math.isfinite(t):
                times.append(t)
        except Exception:
            pass

if len(times) < 2:
    print("0.000")
else:
    print(f"{max(times) - min(times):.6f}")
PY
}

played_duration_sec() {
  local bag="$1"
  python3 - "$bag" "$BAG_START" "$BAG_DURATION" <<'PY'
import sys
import rosbag

bag_path, start_s, duration_s = sys.argv[1], float(sys.argv[2]), float(sys.argv[3])
with rosbag.Bag(bag_path) as bag:
    total = max(0.0, bag.get_end_time() - bag.get_start_time())
remaining = max(0.0, total - max(0.0, start_s))
played = remaining if duration_s <= 0 else min(duration_s, remaining)
print(f"{played:.6f}")
PY
}

extract_metric() {
  local file="$1"
  [ -f "$file" ] || { printf '\n'; return; }
  awk '/rmse/ {print $2; exit}' "$file"
}

sequence_dir() {
  local seq="$1" seq_dir
  seq_dir="$(find "$AQUATIC_ROOT/data" -maxdepth 1 -type d -name "${seq}_*" | sort | head -1)"
  if [ -z "$seq_dir" ] && [ -d "$AQUATIC_ROOT/data/$seq" ]; then seq_dir="$AQUATIC_ROOT/data/$seq"; fi
  [ -n "$seq_dir" ] || return 1
  printf '%s\n' "$seq_dir"
}

bag_for_sequence() {
  local seq_dir="$1"
  find "$seq_dir/data rosbag" -maxdepth 1 -type f -name '*200hz_images_20hz.bag' | sort | head -1
}

image_source_stats() {
  local seq_dir="$1" sensor="$2" out_file="$3"
  python3 "$IMAGE_PUBLISHER" \
    --stats-only \
    --sequence-dir "$seq_dir" \
    --sensor "$sensor" \
    --start "$BAG_START" \
    --duration "$BAG_DURATION" \
    --rate "$BAG_RATE" \
    --max-frames "$MAX_FRAMES" > "$out_file" 2>&1
}

stat_value() {
  local file="$1" key="$2"
  awk -F= -v key="$key" '$1 == key { print $2; found=1; exit } END { if(!found) print "" }' "$file"
}

apply_mode_to_config() {
  local src="$1" dst="$2" mode="$3" adaptive_csv="$4"
  local info_selector info_kf
  read -r info_selector info_kf < <(mode_switches "$mode")
  awk '
    !/^[[:space:]]*(UWIDVO\.Mode|InfoSelector\.Enable|InfoKF\.Use|EnableAdaptiveIDVO|AdaptivePolicyType|EnableAdaptiveLogging|AdaptiveLogPath)[[:space:]]*:/
  ' "$src" > "$dst"
  cat >> "$dst" <<EOF

# Generated by Exp.3 AquaticVision ROS-online script
UWIDVO.Mode: "${mode}"
InfoSelector.Enable: ${info_selector}
InfoKF.Use: ${info_kf}
EnableAdaptiveIDVO: 0
AdaptivePolicyType: "Fixed"
EnableAdaptiveLogging: 1
AdaptiveLogPath: "${adaptive_csv}"
EOF
}

make_launch() {
  local launch_file="$1" sensor="$2" cfg="$3"
  if [ "$sensor" = "mono" ]; then
    cat > "$launch_file" <<EOF
<launch>
  <param name="use_sim_time" value="true"/>
  <node name="orb_slam3" pkg="orb_slam3_ros" type="ros_mono" output="screen">
    <param name="voc_file" type="string" value="${VOCAB}"/>
    <param name="settings_file" type="string" value="${cfg}"/>
    <param name="enable_pangolin" type="bool" value="false"/>
    <remap from="/camera/image_raw" to="/davis_left/image_raw"/>
  </node>
</launch>
EOF
  else
    cat > "$launch_file" <<EOF
<launch>
  <param name="use_sim_time" value="true"/>
  <node name="orb_slam3" pkg="orb_slam3_ros" type="ros_stereo" output="screen">
    <param name="voc_file" type="string" value="${VOCAB}"/>
    <param name="settings_file" type="string" value="${cfg}"/>
    <param name="enable_pangolin" type="bool" value="false"/>
    <remap from="/camera/left/image_raw" to="/davis_left/image_raw"/>
    <remap from="/camera/right/image_raw" to="/davis_right/image_raw"/>
  </node>
</launch>
EOF
  fi
}

copy_saved_outputs() {
  local tag="$1" run_dir="$2"
  local ros_home="${ROS_HOME:-$HOME/.ros}"
  local f base
  for f in "$ros_home/${tag}"*; do
    [ -e "$f" ] || continue
    base="$(basename "$f")"
    cp -f "$f" "$run_dir/$base"
  done
  for f in "$run_dir/${tag}"*_cam_traj.txt "$run_dir/${tag}"*.txt; do
    [ -s "$f" ] || continue
    if echo "$f" | grep -q "_cam_traj.txt"; then cp -f "$f" "$run_dir/trajectory.txt"; break; fi
  done
  for f in "$run_dir/${tag}"*_perf.csv; do
    [ -s "$f" ] || continue
    cp -f "$f" "$run_dir/runtime_perf.csv"
    break
  done
}

run_evo_optional() {
  local gt="$1" traj="$2" evo_dir="$3"
  mkdir -p "$evo_dir"
  if [ ! -s "$gt" ] || [ ! -s "$traj" ]; then echo "EVO_SKIP missing gt or trajectory" > "$evo_dir/evo_status.txt"; return 0; fi
  if ! command -v evo_ape >/dev/null 2>&1 || ! command -v evo_rpe >/dev/null 2>&1 || ! command -v evo_traj >/dev/null 2>&1; then echo "EVO_SKIP evo tools not found" > "$evo_dir/evo_status.txt"; return 0; fi

  local gt_eval="$evo_dir/groundtruth_matched.tum"
  local traj_eval="$evo_dir/estimated_matched.tum"
  python3 - "$gt" "$traj" "$gt_eval" "$traj_eval" <<'PY' > "$evo_dir/match_timestamps_stdout.txt" 2>&1
import bisect, sys
gt_in, est_in, gt_out, est_out = sys.argv[1:5]
def read_tum(path):
    rows=[]
    for line in open(path):
        line=line.strip()
        if not line or line.startswith("#"): continue
        p=line.split()
        if len(p) < 8: continue
        t=float(p[0])
        if abs(t) > 1e12: t /= 1e9
        rows.append((t,p))
    return rows
gt=read_tum(gt_in); est=read_tum(est_in)
if len(gt)<3 or len(est)<3: raise SystemExit("not enough poses")
gt_times=[r[0] for r in gt]
offset=gt_times[0]-est[0][0]
max_dt=0.05
matches=[]
for et, ep in est:
    target=et+offset
    j=bisect.bisect_left(gt_times,target)
    cand=[]
    if j<len(gt): cand.append(j)
    if j>0: cand.append(j-1)
    if not cand: continue
    best=min(cand,key=lambda i: abs(gt_times[i]-target))
    if abs(gt_times[best]-target) <= max_dt:
        matches.append((et, gt[best][1], ep))
if len(matches)<3: raise SystemExit(f"not enough matches {len(matches)}")
with open(gt_out,"w") as fg, open(est_out,"w") as fe:
    for stamp,g,e in matches:
        fg.write(" ".join([f"{stamp:.9f}"]+g[1:8])+"\n")
        fe.write(" ".join([f"{stamp:.9f}"]+e[1:8])+"\n")
print(f"matches={len(matches)}")
print(f"offset={offset:.9f}")
PY

  if [ ! -s "$gt_eval" ] || [ ! -s "$traj_eval" ]; then echo "EVO_SKIP timestamp matching failed" > "$evo_dir/evo_status.txt"; return 0; fi
  export MPLBACKEND=Agg
  echo "EVO_RUNNING" > "$evo_dir/evo_status.txt"
  timeout --preserve-status "$EVO_TIMEOUT" evo_ape tum "$gt_eval" "$traj_eval" -a --align --correct_scale -s -v --save_results "$evo_dir/evo_ape.zip" --save_plot "$evo_dir/evo_ape_plot_xy.pdf" --plot_mode xy --no_warnings > "$evo_dir/evo_ape.txt" 2>&1 || echo "evo_ape failed or timed out" >> "$evo_dir/evo_status.txt"
  timeout --preserve-status "$EVO_TIMEOUT" evo_rpe tum "$gt_eval" "$traj_eval" -a --align --correct_scale -s -v -r trans_part -d 1 -u f --save_results "$evo_dir/evo_rpe.zip" --save_plot "$evo_dir/evo_rpe_plot_xy.pdf" --plot_mode xy --no_warnings > "$evo_dir/evo_rpe.txt" 2>&1 || echo "evo_rpe failed or timed out" >> "$evo_dir/evo_status.txt"
  timeout --preserve-status "$EVO_TIMEOUT" evo_traj tum "$traj_eval" --ref "$gt_eval" --align --correct_scale --save_plot "$evo_dir/evo_traj_plot_xy.pdf" --plot_mode xy --no_warnings > "$evo_dir/evo_traj.txt" 2>&1 || echo "evo_traj failed or timed out" >> "$evo_dir/evo_status.txt"
  echo "EVO_DONE" >> "$evo_dir/evo_status.txt"
}

run_case() {
  local seq="$1" sensor="$2" mode="$3" run_id="$4"
  local run_dir="$RESULT_ROOT/AquaticVision/$seq/$sensor/$mode/run_${run_id}"
  local seq_dir bag base_cfg cfg adaptive_csv launch_file tag start_time end_time elapsed exit_code traj_poses input_frames completeness status notes ate rpe gt played traj_span source_kind stats_file
  mkdir -p "$run_dir"

  source_kind="$(normalize_source "$AQUATIC_SOURCE")" || { write_row "exp3" "AquaticVision" "$seq" "$sensor" "$mode" "$run_id" "SKIP" "" "" "" "" "" "" "$run_dir" "invalid_AQUATIC_SOURCE_$AQUATIC_SOURCE"; return 0; }
  seq_dir="$(sequence_dir "$seq")" || { write_row "exp3" "AquaticVision" "$seq" "$sensor" "$mode" "$run_id" "SKIP" "" "" "" "" "" "" "$run_dir" "missing_sequence_dir"; return 0; }
  bag=""
  if [ "$source_kind" = "rosbag" ]; then
    bag="$(bag_for_sequence "$seq_dir")"
    [ -f "$bag" ] || { write_row "exp3" "AquaticVision" "$seq" "$sensor" "$mode" "$run_id" "SKIP" "" "" "" "" "" "" "$run_dir" "missing_bag"; return 0; }
  else
    [ -x "$IMAGE_PUBLISHER" ] || chmod +x "$IMAGE_PUBLISHER" >/dev/null 2>&1 || true
    [ -d "$seq_dir/Stereo images/l1" ] || { write_row "exp3" "AquaticVision" "$seq" "$sensor" "$mode" "$run_id" "SKIP" "" "" "" "" "" "" "$run_dir" "missing_stereo_images_l1"; return 0; }
    [ -d "$seq_dir/Stereo images/r1" ] || { write_row "exp3" "AquaticVision" "$seq" "$sensor" "$mode" "$run_id" "SKIP" "" "" "" "" "" "" "$run_dir" "missing_stereo_images_r1"; return 0; }
  fi

  if [ "$sensor" = "mono" ]; then base_cfg="$AQUATIC_MONO_CONFIG"; else base_cfg="$AQUATIC_STEREO_CONFIG"; fi
  if [ ! -f "$base_cfg" ]; then
    write_row "exp3" "AquaticVision" "$seq" "$sensor" "$mode" "$run_id" "SKIP" "" "" "" "" "" "" "$run_dir" "missing_base_config"
    return 0
  fi
  adaptive_csv="$run_dir/adaptive_frames.csv"
  cfg="$run_dir/settings.yaml"
  apply_mode_to_config "$base_cfg" "$cfg" "$mode" "$adaptive_csv"
  launch_file="$run_dir/run.launch"
  make_launch "$launch_file" "$sensor" "$cfg"

  tag="exp3_AquaticVision_${seq}_${sensor}_${mode}_r${run_id}"
  rm -f "$HOME/.ros/${tag}"*

  stats_file="$run_dir/input_source_stats.txt"
  if [ "$source_kind" = "stereo_images" ]; then
    if ! image_source_stats "$seq_dir" "$sensor" "$stats_file"; then
      write_row "exp3" "AquaticVision" "$seq" "$sensor" "$mode" "$run_id" "SKIP" "" "" "" "" "" "" "$run_dir" "image_source_stats_failed"
      return 0
    fi
  fi

  log "[RUN] seq=$seq sensor=$sensor mode=$mode run=$run_id source=$source_kind"
  start_time="$(date +%s)"
  set +e
  roslaunch "$launch_file" > "$run_dir/roslaunch.log" 2>&1 &
  local launch_pid=$!
  sleep "$STARTUP_WAIT"
  if [ "$source_kind" = "rosbag" ]; then
    local duration_args=()
    if [ "${BAG_DURATION}" != "0" ]; then duration_args=(--duration "$BAG_DURATION"); fi
    if [ "${RUN_TIMEOUT}" != "0" ]; then
      timeout --preserve-status "$RUN_TIMEOUT" rosbag play --clock -q -s "$BAG_START" -r "$BAG_RATE" "${duration_args[@]}" "$bag" > "$run_dir/rosbag_play.log" 2>&1
      exit_code=$?
    else
      rosbag play --clock -q -s "$BAG_START" -r "$BAG_RATE" "${duration_args[@]}" "$bag" > "$run_dir/rosbag_play.log" 2>&1
      exit_code=$?
    fi
  else
    if [ "${RUN_TIMEOUT}" != "0" ]; then
      timeout --preserve-status "$RUN_TIMEOUT" python3 "$IMAGE_PUBLISHER" --sequence-dir "$seq_dir" --sensor "$sensor" --start "$BAG_START" --duration "$BAG_DURATION" --rate "$BAG_RATE" --max-frames "$MAX_FRAMES" > "$run_dir/image_publisher.log" 2>&1
      exit_code=$?
    else
      python3 "$IMAGE_PUBLISHER" --sequence-dir "$seq_dir" --sensor "$sensor" --start "$BAG_START" --duration "$BAG_DURATION" --rate "$BAG_RATE" --max-frames "$MAX_FRAMES" > "$run_dir/image_publisher.log" 2>&1
      exit_code=$?
    fi
  fi
  timeout --preserve-status "$SAVE_TRAJ_TIMEOUT" rosservice call /orb_slam3/save_traj "$tag" > "$run_dir/save_traj.log" 2>&1
  kill "$launch_pid" >/dev/null 2>&1
  wait "$launch_pid" >/dev/null 2>&1
  set -e
  end_time="$(date +%s)"
  elapsed=$((end_time - start_time))

  copy_saved_outputs "$tag" "$run_dir"
  traj_poses="$(count_lines "$run_dir/trajectory.txt")"
  if [ "$source_kind" = "rosbag" ]; then
    input_frames="$(python3 - "$bag" <<'PY'
import rosbag, sys
bag=rosbag.Bag(sys.argv[1])
topics=['/davis_left/image_raw']
n=sum(1 for _ in bag.read_messages(topics=topics))
bag.close()
print(n)
PY
)"
    played="$(played_duration_sec "$bag")"
  else
    input_frames="$(stat_value "$stats_file" selected_frames)"
    played="$(stat_value "$stats_file" span_sec)"
  fi
  traj_span="$(trajectory_span_sec "$run_dir/trajectory.txt")"
  completeness="$(python3 - "$traj_span" "$played" <<'PY'
import sys
span=float(sys.argv[1]); played=max(1e-9, float(sys.argv[2]))
value=max(0.0, min(100.0, 100.0*span/played))
print(f"{value:.3f}")
PY
)"

  gt="$seq_dir/groundtruth/gt.tum"
  run_evo_optional "$gt" "$run_dir/trajectory.txt" "$run_dir/evo"
  ate="$(extract_metric "$run_dir/evo/evo_ape.txt")"
  rpe="$(extract_metric "$run_dir/evo/evo_rpe.txt")"

  status="PASS"; notes="ok"
  if [ "$traj_poses" -lt "$MIN_TRAJECTORY_POSES" ]; then status="VALIDATION_FAIL"; notes="too_few_trajectory_poses"; elif [ "$exit_code" -ne 0 ]; then status="PASS_WITH_PLAY_EXIT_${exit_code}"; notes="rosbag_play_exit_${exit_code}"; fi

  write_row "exp3" "AquaticVision" "$seq" "$sensor" "$mode" "$run_id" "$status" "$ate" "$rpe" "$completeness" "$traj_poses" "$input_frames" "$elapsed" "$run_dir" "$notes"
}

main() {
  printf 'experiment_id,dataset,sequence,sensor,method,run_id,status,ate_rmse_m,rpe_rmse_m,completeness_percent,trajectory_poses,input_frames,runtime_sec,result_dir,notes\n' > "$SUMMARY"
  log "Exp.3 AquaticVision ROS-online generalization started"
  log "WS=$WS"
  log "AQUATIC_ROOT=$AQUATIC_ROOT"
  log "RUN_TAG=$RUN_TAG"
  log "RUNTIME_MODE=$RUNTIME_MODE"
  log "AQUATIC_SOURCE=$AQUATIC_SOURCE"
  log "SEQUENCES=$SEQUENCES"
  log "SENSORS=$SENSORS"
  log "UWIDVO_MODES=$UWIDVO_MODES"
  log "RUNS_PER_CASE=$RUNS_PER_CASE"
  log "BAG_START=$BAG_START"
  log "BAG_DURATION=$BAG_DURATION"
  log "BAG_RATE=$BAG_RATE"
  log "MAX_FRAMES=$MAX_FRAMES"

  if [ -f /opt/ros/noetic/setup.bash ]; then source /opt/ros/noetic/setup.bash; fi
  if [ "$DO_BUILD" = "1" ]; then catkin build --cmake-args -DORB3_USE_INFOSEL=ON; fi
  if [ -f "$WS/devel/setup.bash" ]; then source "$WS/devel/setup.bash"; fi

  local seq sensor raw_mode mode run_id
  for seq in $SEQUENCES; do
    for sensor in $SENSORS; do
      for raw_mode in $(printf '%s' "$UWIDVO_MODES" | tr ',' ' '); do
        mode="$(normalize_mode "$raw_mode")" || { log "[WARN] skip invalid mode=$raw_mode"; continue; }
        for run_id in $(seq 1 "$RUNS_PER_CASE"); do
          run_case "$seq" "$sensor" "$mode" "$run_id"
        done
      done
    done
  done

  log "Exp.3 finished"
  log "Summary: $SUMMARY"
  log "Raw results: $RESULT_ROOT"
}

main "$@"
