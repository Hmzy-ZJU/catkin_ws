#!/usr/bin/env bash
set -euo pipefail

# Exp. 4: EuRoC MH01-MH05 stereo-inertial offline SOTA comparison.

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
EXP_DIR="$SCRIPT_DIR"
CONFIG_FILE="${EXP4_CONFIG:-$EXP_DIR/run_config/exp4_config.env}"

if [ ! -f "$CONFIG_FILE" ]; then
  echo "[ERROR] missing config: $CONFIG_FILE" >&2
  exit 2
fi

# shellcheck disable=SC1090
source "$CONFIG_FILE"

RUN_TAG="${RUN_TAG:-exp4_euroc_sota_$(date +%Y%m%d_%H%M%S)}"
RESULT_ROOT="$EXP_DIR/raw_results/${RUN_TAG}"
SUMMARY="$EXP_DIR/processed_results/exp4_all_runs_${RUN_TAG}.csv"
MASTER_LOG="$EXP_DIR/logs/${RUN_TAG}.log"

mkdir -p "$RESULT_ROOT" "$EXP_DIR/processed_results" "$EXP_DIR/logs"
: > "$MASTER_LOG"

log() {
  printf '[%s] %s\n' "$(date '+%F %T')" "$*" | tee -a "$MASTER_LOG"
}

csv_quote() {
  printf '"%s"' "$(printf '%s' "$1" | sed 's/"/""/g')"
}

write_row() {
  local first=1 value
  for value in "$@"; do
    if [ "$first" = "1" ]; then first=0; else printf ',' >> "$SUMMARY"; fi
    csv_quote "$value" >> "$SUMMARY"
  done
  printf '\n' >> "$SUMMARY"
}

normalize_mode() {
  local upper
  upper="$(printf '%s' "$1" | tr '[:lower:]-' '[:upper:]_')"
  case "$upper" in
    ORB_SLAM3|ORBSLAM3|ORB3|BASELINE) printf '%s\n' ORB_SLAM3 ;;
    IDPS) printf '%s\n' IDPS ;;
    IDKD) printf '%s\n' IDKD ;;
    IDVO|UW_IDVO|UWIDVO) printf '%s\n' IDVO ;;
    *) return 1 ;;
  esac
}

mode_switches() {
  case "$1" in
    ORB_SLAM3) printf '%s %s\n' 0 0 ;;
    IDPS) printf '%s %s\n' 1 0 ;;
    IDKD) printf '%s %s\n' 0 1 ;;
    IDVO) printf '%s %s\n' 1 1 ;;
    *) return 1 ;;
  esac
}

find_exe() {
  local name="$1"
  for p in \
    "$WS/devel/.private/orb_slam3_ros/lib/orb_slam3_ros/$name" \
    "$WS/devel/lib/orb_slam3_ros/$name" \
    "$WS/build/orb_slam3_ros/$name"; do
    if [ -x "$p" ]; then printf '%s\n' "$p"; return 0; fi
  done
  return 1
}

count_lines() {
  local file="$1"
  [ -f "$file" ] || { printf '0\n'; return; }
  awk 'NF && $1 !~ /^#/ { c++ } END { print c+0 }' "$file"
}

apply_mode_to_config() {
  local src="$1" dst="$2" mode="$3" adaptive_csv="$4"
  local info_selector info_kf
  read -r info_selector info_kf < <(mode_switches "$mode")
  awk '
    !/^[[:space:]]*(UWIDVO\.Mode|InfoSelector\.Enable|InfoKF\.Use|EnableAdaptiveIDVO|AdaptivePolicyType|EnableAdaptiveLogging|AdaptiveLogPath)[[:space:]]*:/
  ' "$src" > "$dst"
  cat >> "$dst" <<EOF

# Generated by Exp.4 EuRoC SOTA script
UWIDVO.Mode: "${mode}"
InfoSelector.Enable: ${info_selector}
InfoKF.Use: ${info_kf}
EnableAdaptiveIDVO: 0
AdaptivePolicyType: "Fixed"
EnableAdaptiveLogging: 1
AdaptiveLogPath: "${adaptive_csv}"
EOF
}

find_gt() {
  local seq="$1"
  for p in \
    "$EUROC_ROOT/GT/${seq}.csv" \
    "$EUROC_ROOT/GT/${seq}.tum" \
    "$EUROC_ROOT/GT/${seq}.txt" \
    "$EUROC_ROOT/groundtruth/${seq}.tum" \
    "$EUROC_ROOT/groundtruth/${seq}.txt"; do
    if [ -s "$p" ]; then printf '%s\n' "$p"; return 0; fi
  done
  return 1
}

gt_to_tum() {
  local src="$1" dst="$2"
  case "$src" in
    *.tum|*.txt)
      cp -f "$src" "$dst"
      ;;
    *.csv)
      python3 - "$src" "$dst" <<'PY'
import csv
import math
import sys

src, dst = sys.argv[1:3]

def norm_stamp(v):
    t = float(v)
    if abs(t) > 1e12:
        t *= 1e-9
    return t

with open(src, newline="") as f:
    sample = f.readline()
    f.seek(0)
    if sample.lstrip().startswith("#"):
        header = [x.strip().lstrip("#").strip() for x in sample.strip().split(",")]
        reader = csv.DictReader(f, fieldnames=header)
        next(reader, None)
    else:
        reader = csv.DictReader(f)

    rows = []
    for row in reader:
        if not row:
            continue
        try:
            # EuRoC groundtruth CSV convention:
            # timestamp, p_RS_R_x, p_RS_R_y, p_RS_R_z, q_RS_w, q_RS_x, q_RS_y, q_RS_z
            stamp_key = next((k for k in row if "timestamp" in k.lower()), None)
            if stamp_key is None:
                keys = list(row.keys())
                vals = [row[k] for k in keys]
                t = norm_stamp(vals[0])
                x, y, z = map(float, vals[1:4])
                qw, qx, qy, qz = map(float, vals[4:8])
            else:
                t = norm_stamp(row[stamp_key])
                x = float(row.get("p_RS_R_x", row.get("tx", row.get("x"))))
                y = float(row.get("p_RS_R_y", row.get("ty", row.get("y"))))
                z = float(row.get("p_RS_R_z", row.get("tz", row.get("z"))))
                qw = float(row.get("q_RS_w", row.get("qw", "1")))
                qx = float(row.get("q_RS_x", row.get("qx", "0")))
                qy = float(row.get("q_RS_y", row.get("qy", "0")))
                qz = float(row.get("q_RS_z", row.get("qz", "0")))
            if all(math.isfinite(v) for v in (t, x, y, z, qx, qy, qz, qw)):
                rows.append((t, x, y, z, qx, qy, qz, qw))
        except Exception:
            continue

with open(dst, "w") as out:
    for r in rows:
        out.write("%.9f %.9f %.9f %.9f %.9f %.9f %.9f %.9f\n" % r)

print(f"converted={len(rows)}")
PY
      ;;
    *)
      return 1
      ;;
  esac
}

extract_metric() {
  local file="$1"
  [ -f "$file" ] || { printf '\n'; return; }
  awk '/rmse/ {print $2; exit}' "$file"
}

run_evo_optional() {
  local gt="$1" traj="$2" evo_dir="$3"
  mkdir -p "$evo_dir"
  if [ ! -s "$gt" ]; then
    echo "EVO_SKIP missing groundtruth" > "$evo_dir/evo_status.txt"
    return 0
  fi
  if [ ! -s "$traj" ]; then
    echo "EVO_SKIP missing trajectory" > "$evo_dir/evo_status.txt"
    return 0
  fi
  if ! command -v evo_ape >/dev/null 2>&1 || ! command -v evo_rpe >/dev/null 2>&1 || ! command -v evo_traj >/dev/null 2>&1; then
    echo "EVO_SKIP evo tools not found" > "$evo_dir/evo_status.txt"
    return 0
  fi

  local gt_eval="$evo_dir/groundtruth_matched.tum"
  local traj_eval="$evo_dir/estimated_matched.tum"
  python3 - "$gt" "$traj" "$gt_eval" "$traj_eval" <<'PY' > "$evo_dir/match_timestamps_stdout.txt" 2>&1
import bisect
import sys

gt_in, est_in, gt_out, est_out = sys.argv[1:5]

def read_tum(path):
    rows = []
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split()
            if len(parts) < 8:
                continue
            stamp = float(parts[0])
            if abs(stamp) > 1e12:
                stamp /= 1e9
            rows.append((stamp, parts))
    return rows

gt = read_tum(gt_in)
est = read_tum(est_in)
if len(gt) < 3 or len(est) < 3:
    raise SystemExit(f"not enough poses for evo matching: gt={len(gt)}, est={len(est)}")

gt_times = [r[0] for r in gt]
offset = gt_times[0] - est[0][0]
window_count = min(20, len(gt_times) - 1)
window_span = gt_times[window_count] - gt_times[0] if window_count > 0 else 0.05
max_dt = max(0.05, 2.5 * window_span / max(1, window_count))
matches = []
for est_t, est_parts in est:
    target = est_t + offset
    j = bisect.bisect_left(gt_times, target)
    cand = []
    if j < len(gt):
        cand.append(j)
    if j > 0:
        cand.append(j - 1)
    if not cand:
        continue
    best = min(cand, key=lambda i: abs(gt_times[i] - target))
    dt = abs(gt_times[best] - target)
    if dt <= max_dt:
        matches.append((est_t, gt[best][1], est_parts, dt))

if len(matches) < 3:
    raise SystemExit(f"not enough matched poses: {len(matches)}, offset={offset}, max_dt={max_dt}")

with open(gt_out, "w") as fg, open(est_out, "w") as fe:
    for stamp, gt_parts, est_parts, _ in matches:
        fg.write(" ".join([f"{stamp:.9f}"] + gt_parts[1:8]) + "\n")
        fe.write(" ".join([f"{stamp:.9f}"] + est_parts[1:8]) + "\n")

mean_dt = sum(m[3] for m in matches) / len(matches)
print(f"matches={len(matches)}")
print(f"offset={offset:.9f}")
print(f"max_dt={max_dt:.9f}")
print(f"mean_dt={mean_dt:.9f}")
PY

  if [ ! -s "$gt_eval" ] || [ ! -s "$traj_eval" ]; then
    echo "EVO_SKIP failed to create matched TUM files" > "$evo_dir/evo_status.txt"
    return 0
  fi

  export MPLBACKEND=Agg
  echo "EVO_RUNNING" > "$evo_dir/evo_status.txt"
  timeout --preserve-status "$EVO_TIMEOUT" evo_ape tum "$gt_eval" "$traj_eval" -a --align --correct_scale -s -v --save_results "$evo_dir/evo_ape.zip" --save_plot "$evo_dir/evo_ape_plot_xy.pdf" --plot_mode xy --no_warnings > "$evo_dir/evo_ape.txt" 2>&1 || echo "evo_ape failed or timed out" >> "$evo_dir/evo_status.txt"
  timeout --preserve-status "$EVO_TIMEOUT" evo_rpe tum "$gt_eval" "$traj_eval" -a --align --correct_scale -s -v -r trans_part -d 1 -u f --save_results "$evo_dir/evo_rpe.zip" --save_plot "$evo_dir/evo_rpe_plot_xy.pdf" --plot_mode xy --no_warnings > "$evo_dir/evo_rpe.txt" 2>&1 || echo "evo_rpe failed or timed out" >> "$evo_dir/evo_status.txt"
  timeout --preserve-status "$EVO_TIMEOUT" evo_traj tum "$traj_eval" --ref "$gt_eval" --align --correct_scale --save_plot "$evo_dir/evo_traj_plot_xy.pdf" --plot_mode xy --no_warnings > "$evo_dir/evo_traj.txt" 2>&1 || echo "evo_traj failed or timed out" >> "$evo_dir/evo_status.txt"
  echo "EVO_DONE" >> "$evo_dir/evo_status.txt"
}

run_case() {
  local seq="$1" mode="$2" run_id="$3"
  local bag="$EUROC_ROOT/data/${seq}.bag"
  local cache="$EUROC_CACHE_ROOT/${seq}"
  local run_dir="$RESULT_ROOT/EuRoC/${seq}/${SENSOR}/${mode}/run_${run_id}"
  local adaptive_csv="$run_dir/adaptive_frames.csv"
  local cfg="$run_dir/settings.yaml"
  local exe tag traj input_frames traj_poses completeness status notes start_time end_time elapsed exit_code gt gt_tum ate rpe

  mkdir -p "$run_dir"
  if [ ! -f "$bag" ]; then
    write_row "exp4" "EuRoC" "$seq" "$SENSOR" "$mode" "$run_id" "SKIP" "" "" "" "" "" "" "" "" "$run_dir" "missing_bag"
    return 0
  fi

  if [ ! -f "$cache/timestamps.txt" ] || [ ! -d "$cache/mav0/cam0/data" ]; then
    log "[EXTRACT] seq=$seq bag=$bag cache=$cache"
    python3 "$EXTRACT_TOOL" --dataset euroc --bag "$bag" --out "$cache" --start "$BAG_START" --duration "$BAG_DURATION" --max-frames "$MAX_FRAMES" > "$run_dir/extract_stdout.txt" 2>&1
  fi

  apply_mode_to_config "$BASE_CONFIG" "$cfg" "$mode" "$adaptive_csv"
  exe="$(find_exe aidvo_offline_stereo_inertial_euroc)" || {
    write_row "exp4" "EuRoC" "$seq" "$SENSOR" "$mode" "$run_id" "SKIP" "" "" "" "" "" "" "" "" "$run_dir" "missing_executable"
    return 0
  }

  tag="exp4_${seq}_${SENSOR}_${mode}_r${run_id}"
  traj="$run_dir/f_${tag}.txt"

  log "[RUN] seq=$seq sensor=$SENSOR mode=$mode run=$run_id"
  start_time="$(date +%s)"
  set +e
  (
    cd "$run_dir"
    AIDVO_OFFLINE_REALTIME=0 "$exe" "$VOCAB" "$cfg" "$cache" "$cache/timestamps.txt" "$tag" > offline_stdout.txt 2>&1
  )
  exit_code=$?
  set -e
  end_time="$(date +%s)"
  elapsed=$((end_time - start_time))

  [ -f "$traj" ] && cp -f "$traj" "$run_dir/trajectory.txt"
  input_frames="$(count_lines "$cache/timestamps.txt")"
  traj_poses="$(count_lines "$traj")"
  completeness="$(python3 - "$traj_poses" "$input_frames" <<'PY'
import sys
poses=int(sys.argv[1]); frames=max(1,int(sys.argv[2]))
print(f"{100.0*poses/frames:.3f}")
PY
)"

  status="PASS"
  notes="ok"
  if [ "$traj_poses" -lt "$MIN_TRAJECTORY_POSES" ]; then
    status="VALIDATION_FAIL"
    notes="too_few_trajectory_poses"
  elif ! python3 - "$completeness" "$MIN_COMPLETENESS" <<'PY'
import sys
raise SystemExit(0 if float(sys.argv[1]) >= float(sys.argv[2]) else 1)
PY
  then
    status="VALIDATION_FAIL"
    notes="low_completeness"
  elif [ "$exit_code" -ne 0 ]; then
    status="PASS_WITH_EXIT_${exit_code}"
    notes="trajectory_saved_but_exit_${exit_code}"
  fi

  gt=""
  if gt="$(find_gt "$seq")"; then
    gt_tum="$run_dir/groundtruth.tum"
    if gt_to_tum "$gt" "$gt_tum" > "$run_dir/gt_convert_stdout.txt" 2>&1; then
      run_evo_optional "$gt_tum" "$traj" "$run_dir/evo"
    else
      mkdir -p "$run_dir/evo"
      echo "EVO_SKIP failed to convert GT: $gt" > "$run_dir/evo/evo_status.txt"
    fi
  else
    mkdir -p "$run_dir/evo"
    echo "EVO_SKIP missing EuRoC GT for $seq" > "$run_dir/evo/evo_status.txt"
  fi
  ate="$(extract_metric "$run_dir/evo/evo_ape.txt")"
  rpe="$(extract_metric "$run_dir/evo/evo_rpe.txt")"
  if [ -z "$ate" ] || [ -z "$rpe" ]; then
    local evo_note
    evo_note="$(tr '\n' ';' < "$run_dir/evo/evo_status.txt" 2>/dev/null || printf 'missing_evo_status')"
    if [ "$status" = "PASS" ]; then
      status="PASS_NO_EVO"
    fi
    notes="${notes};evo_missing_metrics:${evo_note}"
  fi

  write_row "exp4" "EuRoC" "$seq" "$SENSOR" "$mode" "$run_id" "$status" "$ate" "$rpe" "$completeness" "$traj_poses" "$input_frames" "$elapsed" "$cfg" "$traj" "$run_dir" "$notes"
}

main() {
  printf 'experiment_id,dataset,sequence,sensor,method,run_id,status,ate_rmse_m,rpe_rmse_m,completeness_percent,trajectory_poses,input_frames,runtime_sec,settings_file,trajectory_file,result_dir,notes\n' > "$SUMMARY"
  log "Exp.4 EuRoC SOTA comparison started"
  log "WS=$WS"
  log "EUROC_ROOT=$EUROC_ROOT"
  log "RUN_TAG=$RUN_TAG"
  log "SEQUENCES=$SEQUENCES"
  log "SENSOR=$SENSOR"
  log "UWIDVO_MODES=$UWIDVO_MODES"
  log "RUNS_PER_CASE=$RUNS_PER_CASE"

  if [ -f /opt/ros/noetic/setup.bash ]; then source /opt/ros/noetic/setup.bash; fi
  if [ "$DO_BUILD" = "1" ]; then catkin build --cmake-args -DORB3_USE_INFOSEL=ON; fi
  if [ -f "$WS/devel/setup.bash" ]; then source "$WS/devel/setup.bash"; fi

  local seq raw_mode mode run_id
  for seq in $SEQUENCES; do
    for raw_mode in $(printf '%s' "$UWIDVO_MODES" | tr ',' ' '); do
      mode="$(normalize_mode "$raw_mode")" || { log "[WARN] skip invalid mode=$raw_mode"; continue; }
      for run_id in $(seq 1 "$RUNS_PER_CASE"); do
        run_case "$seq" "$mode" "$run_id"
      done
    done
  done

  log "Exp.4 finished"
  log "Summary: $SUMMARY"
  log "Raw results: $RESULT_ROOT"
  log "Evo plot files:"
  find "$RESULT_ROOT" -type f \( -name "evo_ape_plot_xy.pdf" -o -name "evo_rpe_plot_xy.pdf" -o -name "evo_traj_plot_xy.pdf" \) | sort | tee "$RESULT_ROOT/evo_plots.txt" | tee -a "$MASTER_LOG"
}

main "$@"
